class AppSvgIcon extends StatelessWidget {
  const AppSvgIcon({
    super.key,
    required this.asset,
    this.size = 24,
    this.color,
  });

  final String asset;
  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final bool preserveOriginalColors = AppIcons._multiColorAssets.contains(
      asset,
    );

    if (asset.toLowerCase().endsWith('.png')) {
      return Image.asset(asset, width: size, height: size, fit: BoxFit.contain);
    }

    return SvgPicture.asset(
      asset,
      width: size,
      height: size,
      colorFilter: (color == null || preserveOriginalColors)
          ? null
          : ColorFilter.mode(color!, BlendMode.srcIn),
    );
  }
}
